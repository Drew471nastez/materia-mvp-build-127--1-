import type { DesignReference, PaletteColor, ReferenceDensity, ReferenceRole } from "./types"

const ADDED = "2026-11-10"

interface Seed {
  id: string
  title: string
  summary: string
  styles: string[]
  industries: string[]
  tone: string[]
  density: ReferenceDensity
  mode: "light" | "dark" | "mixed"
  /** "background #111111, text #f2f2f2, accent #e4ff3a" */
  colors: string
  palette: string
  display: string
  body: string
  type: string
  topology: string
  hero: string
  grid: string
  rhythm: string
  imagery: string
  motion: string
  motionIdeas: string[]
  details: string[]
  borrow: string[]
  avoid: string[]
  poor: string[]
  roles: ReferenceRole[]
  quality?: number
}

function colorsOf(spec: string): PaletteColor[] {
  return spec.split(",").map((part) => {
    const m = part.trim().match(/^(.+?)\s+(#[0-9a-fA-F]{6})$/)
    if (!m) throw new Error(`bad colour "${part}"`)
    return { role: m[1].trim(), hex: m[2].toLowerCase() }
  })
}

/** Every seed avoids the same three things on top of its own list. */
const ALWAYS_AVOID = "Do not trace this composition: change proportions, sequence and details for the creator's own content."

function seed(s: Seed): DesignReference {
  return {
    id: s.id,
    version: 1,
    kind: "site",
    title: s.title,
    summary: s.summary,
    styleTags: s.styles,
    industries: s.industries,
    tone: s.tone,
    density: s.density,
    palette: { mode: s.mode, colors: colorsOf(s.colors), strategy: s.palette },
    type: { display: s.display, body: s.body, strategy: s.type },
    layout: { topology: s.topology, hero: s.hero, grid: s.grid, rhythm: s.rhythm },
    imagery: s.imagery,
    motion: { character: s.motion, evidence: "suggested", ideas: s.motionIdeas },
    details: s.details,
    borrow: s.borrow,
    avoid: [...s.avoid, ALWAYS_AVOID],
    fitsPoorly: s.poor,
    roles: s.roles,
    source: { origin: "storelib", url: null, subject: null, creator: "Storelib", capturedAt: null },
    rights: { usage: "analysis_only", licence: null, mayRedistribute: true, notice: "Storelib's own description of a design pattern. Learn the principles; never reproduce a specific website.", permissionEvidence: null },
    provenance: { addedBy: "storelib", addedAt: ADDED, repo: null, commit: null, path: null, analysisModel: null, verifiedByHuman: true },
    quality: s.quality ?? 4,
    image: null,
    enabled: true,
  }
}

