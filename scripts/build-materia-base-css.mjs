#!/usr/bin/env node
/*
  Materia's combined stylesheet, theme-packages/materia/base/assets/base.css.

  The live store links one render-blocking stylesheet (layout/theme.liquid,
  `use_base_css`): these source files in this cascade order, with comments
  and blank lines taken out. The builder (design mode), stores without scroll
  animation and right-to-left stores link the sources one by one, so the
  sources stay the files to edit. Run this after editing any of them:

    node scripts/build-materia-base-css.mjs          writes base.css and base-static.css
    node scripts/build-materia-base-css.mjs --check  exits 1 when either is stale

  base-static.css is the same bundle without animation.css, for stores whose
  Scroll animation is None (they never linked animation.css). Before it they
  linked the eleven other sources one by one, eleven render-blocking requests.

  tests/theme-templates.test.ts runs the check.
*/
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

export const BASE_CSS_SOURCES = [
  "critical.css",
  "section-isolation.css",
  "animation.css",
  "product-card.css",
  "swiper-bundle.min.css",
  "theme.css",
  "theme-button-contract.css",
  "localization-controls.css",
  "product-block-runtime.css",
  "layout-guard.css",
  "late-css-guard.css",
  "section-type.css",
]

/** CSS without its comments: a comment is never inside a string or a url(), which are kept as written. */
export function stripCssComments(css) {
  let out = ""
  let i = 0
  while (i < css.length) {
    const c = css[i]
    if (c === '"' || c === "'") {
      let j = i + 1
      while (j < css.length && css[j] !== c) j += css[j] === "\\" ? 2 : 1
      out += css.slice(i, j + 1)
      i = j + 1
    } else if (c === "/" && css[i + 1] === "*") {
      const end = css.indexOf("*/", i + 2)
      i = end < 0 ? css.length : end + 2
    } else {
      out += c
      i++
    }
  }
  return out
}

/** The bundles written, each with its sources in cascade order. */
export const BASE_CSS_BUNDLES = {
  "base.css": BASE_CSS_SOURCES,
  "base-static.css": BASE_CSS_SOURCES.filter((name) => name !== "animation.css"),
}

export function buildBaseCss(assetsDir, file = "base.css") {
  const sources = BASE_CSS_BUNDLES[file]
  const head = `/* ${file}: GENERATED by scripts/build-materia-base-css.mjs from ${sources.join(", ")}. Do not edit by hand: edit those files and rebuild. */`
  const parts = sources.map((name) => {
    const body = stripCssComments(readFileSync(join(assetsDir, name), "utf8"))
      .split("\n")
      .filter((line) => line.trim())
      .join("\n")
    return `/* ---- ${name} ---- */\n${body}`
  })
  return `${head}\n${parts.join("\n")}\n`
}

/* Run as a script only (a test that imports buildBaseCss is bundled into a file of its own). */
const isMain = /build-materia-base-css\.mjs$/.test(process.argv[1] ?? "") && import.meta.url.endsWith("/build-materia-base-css.mjs")
if (isMain) {
  const assets = join(process.cwd(), "theme-packages", "materia", "base", "assets")
  for (const name of Object.keys(BASE_CSS_BUNDLES)) {
    const built = buildBaseCss(assets, name)
    const file = join(assets, name)
    if (process.argv.includes("--check")) {
      let now = ""
      try { now = readFileSync(file, "utf8") } catch {}
      if (now !== built) {
        console.error(`${name} is out of date: run node scripts/build-materia-base-css.mjs`)
        process.exit(1)
      }
      console.log(`${name} is up to date`)
    } else {
      writeFileSync(file, built)
      console.log(`wrote ${file} (${built.length} bytes)`)
    }
  }
}
