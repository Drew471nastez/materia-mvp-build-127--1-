/**
 * Writes lib/storelib-ai/library/index.generated.ts from the
 * markdown entries under lib/storelib-ai/library/entries.
 *
 * The runtime cannot read the markdown (nothing imports it, so the serverless
 * bundle never has it), so the text is embedded in a module that is checked
 * in. Parsing and validation stay in TypeScript (library/parse.ts);
 * this only copies files, sorted, so the output is byte stable.
 *
 *   node scripts/build-library.mjs          write it
 *   node scripts/build-library.mjs --check  exit 1 when it is stale
 */
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from "node:fs"
import { join, relative } from "node:path"

const ROOT = "lib/storelib-ai/library"
const ENTRIES = join(ROOT, "entries")
const OUT = join(ROOT, "index.generated.ts")

function walk(dir) {
  return readdirSync(dir).sort().flatMap((name) => {
    const p = join(dir, name)
    return statSync(p).isDirectory() ? walk(p) : name.endsWith(".md") ? [p] : []
  })
}

const files = walk(ENTRIES)
const items = files.map((f) => ({ file: relative(ROOT, f).split("\\").join("/"), source: readFileSync(f, "utf8").replace(/\r\n/g, "\n") }))
const text = `/* Generated by scripts/build-library.mjs from ./entries. Do not edit; edit the markdown and run the script. */\n\nexport const KNOWLEDGE_SOURCES: readonly { file: string; source: string }[] = ${JSON.stringify(items, null, 1)}\n`

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : ""
  if (current !== text) {
    console.error(`${OUT} is stale: run node scripts/build-library.mjs`)
    process.exit(1)
  }
  console.log(`${OUT} is current (${items.length} entries)`)
} else {
  writeFileSync(OUT, text)
  console.log(`wrote ${OUT} (${items.length} entries)`)
}
