#!/usr/bin/env node
/**
 * ===========================================================================
 *  A ROW WITH A LABEL AT EACH END, IN A COLUMN THAT IS SOMETIMES NARROW
 * ===========================================================================
 * Reported with a picture of the design panel: "Advanced colors" broken over
 * two lines, "Using scheme" broken over two lines beside it, and the row
 * twice the height it is drawn as.
 *
 * The cause is a flexbox default nobody sets and everybody meets. A flex
 * item's `min-width` is `auto`, which means it will not shrink below the
 * width of its own content. Two items in a row that has run out of width
 * therefore do not shrink at all — the text inside them wraps instead, both
 * at once, and the row grows.
 *
 * The scheme trigger directly above it has never had this problem because it
 * carries the three things that fix it: `min-w-0` so a child MAY shrink,
 * `truncate` on the part allowed to lose characters, `shrink-0` on the part
 * that is not.
 *
 * This renders the row BOTH WAYS at five widths and measures them, so what
 * is asserted is that the old markup really does wrap and the new markup
 * really does not, rather than that the new markup looks reasonable.
 *
 *   node scripts/check-panel-rows.mjs
 *
 * ---------------------------------------------------------------------------
 *  WHAT THIS CAN AND CANNOT SEE
 * ---------------------------------------------------------------------------
 * The utility classes are written out as plain CSS here, because the real
 * ones are generated by Tailwind at build time and there is no stylesheet on
 * disk to point a browser at. What that means is that this measures the
 * LAYOUT RULE, not the class names: tests/sheet-controls.test.ts is what
 * checks the component still carries the classes this is standing in for.
 */
import { execFileSync } from "node:child_process"
import { writeFileSync, rmSync, existsSync, mkdirSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const CHROMIUM = process.env.CHROMIUM ?? "/opt/pw-browsers/chromium"

const fail = (m) => { console.error(`\n${m}\n`); process.exit(1) }
if (!existsSync(CHROMIUM)) fail(`No browser at ${CHROMIUM}. Set CHROMIUM=/path/to/chromium.`)

const work = join(root, ".panel-rows-probe")
mkdirSync(work, { recursive: true })

/* The widths a sheet panel is really given, down to a very narrow phone. */
const WIDTHS = [360, 300, 260, 220, 180]

try {
  const page = join(work, "rows.html")
  writeFileSync(page, `<!doctype html><meta charset="utf-8">
<style>
  * { box-sizing: border-box; }
  body { margin: 0; background: #fff; font-family: Inter, system-ui, sans-serif; }

  /* The row, both ways. Everything here is the plain CSS behind the utility
     classes the component uses; see the note in check-panel-rows.mjs. */
  .row {
    width: 100%;
    display: flex;
    align-items: center;
    justify-content: space-between;
    padding: 0 12px;              /* px-3 */
    font-size: 14px;              /* text-sm */
    line-height: 20px;
    border: 1px solid #e5e7eb;
    border-radius: 8px;
    background: #fff;
  }
  .row .name { font-weight: 500; color: #0a0a0a; }
  .row .status { display: flex; align-items: center; gap: 8px; font-size: 12px; color: #737373; }
  .row .chev { width: 14px; height: 14px; flex: 0 0 14px; background: #737373; }

  /* BEFORE: h-10, no gap, no min-w-0, no truncate, no shrink-0. */
  .before { height: 40px; }

  /* AFTER: the three rules, plus a row that is a thumb's height. */
  .after { height: 44px; gap: 8px; overflow: hidden; }
  .after .name { flex: 0 0 auto; white-space: nowrap; }
  .after .status { min-width: 0; }
  .after .status > .text { overflow: hidden; text-overflow: ellipsis; white-space: nowrap; }
</style>
<div id="stage"></div>
<pre id="out">pending</pre>
<script>
const WIDTHS = ${JSON.stringify(WIDTHS)}
const stage = document.getElementById("stage")

function build(kind, width, status) {
  const holder = document.createElement("div")
  holder.style.width = width + "px"
  holder.style.padding = "8px 0"
  holder.innerHTML =
    '<div class="row ' + kind + '">' +
      '<span class="name">Advanced colors</span>' +
      '<span class="status"><span class="text">' + status + '</span><span class="chev"></span></span>' +
    '</div>'
  stage.appendChild(holder)
  return holder.querySelector(".row")
}

/* One line or two, measured rather than guessed: a span's client height
   against the line height it was given. */
function lines(el) {
  return Math.max(1, Math.round(el.getBoundingClientRect().height / parseFloat(getComputedStyle(el).lineHeight)))
}

const results = []
for (const width of WIDTHS) {
  for (const kind of ["before", "after"]) {
    for (const status of ["Using scheme", "12 customized"]) {
      const row = build(kind, width, status)
      const name = row.querySelector(".name")
      const text = row.querySelector(".text")
      const chev = row.querySelector(".chev")
      results.push({
        width, kind, status,
        rowHeight: Math.round(row.getBoundingClientRect().height),
        nameLines: lines(name),
        statusLines: lines(text),
        chevWidth: Math.round(chev.getBoundingClientRect().width),
        /* Losing characters to an ellipsis, which is the intended give. */
        statusClipped: text.scrollWidth > text.clientWidth + 1,
      })
    }
  }
}
document.getElementById("out").textContent = JSON.stringify(results)
</script>`)

  const dom = execFileSync(CHROMIUM, [
    "--headless=new", "--no-sandbox", "--disable-gpu", "--window-size=800,900",
    "--virtual-time-budget=6000", "--dump-dom", `file://${page}`,
  ], { encoding: "utf8", maxBuffer: 32 * 1024 * 1024, stdio: ["ignore", "pipe", "ignore"] })

  const match = dom.match(/<pre id="out">([^<]*)</)
  if (!match || match[1] === "pending") fail("The rows never reported a measurement.")
  const rows = JSON.parse(match[1].replace(/&quot;/g, '"').replace(/&amp;/g, "&"))

  let broken = 0
  const expect = (ok, what, got) => {
    console.log(`  ${ok ? "ok  " : "FAIL"}  ${what}${ok ? "" : `   ${got}`}`)
    if (!ok) broken++
  }

  console.log("\nAdvanced colors, with the status beside it, at five column widths\n")
  console.log("  width  markup   status          row   name   status")
  for (const r of rows) {
    console.log(
      `  ${String(r.width).padStart(5)}  ${r.kind.padEnd(7)}  ${r.status.padEnd(14)}  ${String(r.rowHeight).padStart(3)}px  ${r.nameLines} line  ${r.statusLines} line${r.statusClipped ? "  (clipped)" : ""}`,
    )
  }
  console.log("")

  const before = rows.filter((r) => r.kind === "before")
  const after = rows.filter((r) => r.kind === "after")

  /* ── THE PROBE CAN SEE THE BUG ───────────────────────────────────────── */
  const wrapped = before.filter((r) => r.nameLines > 1 || r.statusLines > 1)
  expect(
    wrapped.length > 0,
    "the markup that was reported really does wrap, so this is measuring something",
    "no width made the old row wrap; the fixture no longer reproduces the report",
  )
  console.log(`  it wrapped at ${[...new Set(wrapped.map((r) => r.width))].join(", ")}px\n`)

  /* ── AND THE FIX HOLDS AT EVERY WIDTH ────────────────────────────────── */
  const nameWrapped = after.filter((r) => r.nameLines > 1)
  expect(nameWrapped.length === 0, "the control's name is one line at every width", `${nameWrapped.length} of ${after.length} wrapped`)

  const statusWrapped = after.filter((r) => r.statusLines > 1)
  expect(statusWrapped.length === 0, "and so is the status beside it", `${statusWrapped.length} of ${after.length} wrapped`)

  const heights = [...new Set(after.map((r) => r.rowHeight))]
  expect(heights.length === 1 && heights[0] === 44, "the row is one height, and it is a thumb's height", `heights: ${heights.join(", ")}`)

  const chevs = [...new Set(after.map((r) => r.chevWidth))]
  expect(chevs.length === 1 && chevs[0] === 14, "the chevron is never squeezed", `widths: ${chevs.join(", ")}`)

  /* The give has to land somewhere, and this is where it was chosen to. */
  const narrow = after.filter((r) => r.width <= 220)
  expect(
    narrow.some((r) => r.statusClipped),
    "at the narrowest widths it is the status that gives up characters, not the name",
    "nothing was clipped, so the row is overflowing instead",
  )

  console.log(`\n${broken === 0 ? "One line each, one row height, at every width the panel is given." : `${broken} failed`}`)
  process.exit(broken === 0 ? 0 : 1)
} finally {
  rmSync(work, { recursive: true, force: true })
}
