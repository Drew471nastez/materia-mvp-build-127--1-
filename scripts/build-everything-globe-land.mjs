/**
 * ===========================================================================
 *  THE LAND ON THE "SELL ANYWHERE" GLOBE, ONE BIT PER DOT
 * ===========================================================================
 * The globe in the home page's everything section (everything-globe.tsx)
 * draws a dot wherever there is land. The dots sit in rows of latitude STEP
 * degrees apart, each row holding as many dots as fit around the globe at
 * that latitude (so they are evenly spaced everywhere, poles included), and
 * every other row is shifted half a dot so the rows nest. Each dot is tested
 * against Natural Earth's 1:50m land outline (public domain, through the
 * world-atlas package) at its own centre, so coastlines are as exact as the
 * grid allows, with no second resampling of a coarser bitmap.
 *
 * everything-globe.tsx walks the same rows in the same order to read the
 * bits back (`everythingLandPoints`), so the loop below and that one have
 * to stay the same loop.
 *
 *   node scripts/build-everything-globe-land.mjs [land-50m.json]
 */
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

export const STEP = 1.15
export const NORTH = 83.5
export const SOUTH = -57

const SOURCE = "https://cdn.jsdelivr.net/npm/world-atlas@2/land-50m.json"
const OUT = "components/marketing/home/everything-globe-land.ts"

const topo = process.argv[2] ? JSON.parse(readFileSync(process.argv[2], "utf8")) : await (await fetch(SOURCE)).json()

const { scale, translate } = topo.transform
const arcs = topo.arcs.map((arc) => {
  let x = 0
  let y = 0
  return arc.map(([dx, dy]) => {
    x += dx
    y += dy
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]]
  })
})
const ringOf = (ids) => {
  const out = []
  for (const id of ids) {
    const pts = id < 0 ? arcs[~id].slice().reverse() : arcs[id]
    out.push(...(out.length ? pts.slice(1) : pts))
  }
  return out
}
const rings = []
for (const g of topo.objects.land.geometries) {
  const polys = g.type === "Polygon" ? [g.arcs] : g.arcs
  for (const poly of polys)
    for (const r of poly) {
      const ring = ringOf(r)
      let x0 = Infinity, x1 = -Infinity, y0 = Infinity, y1 = -Infinity
      for (const [x, y] of ring) {
        if (x < x0) x0 = x
        if (x > x1) x1 = x
        if (y < y0) y0 = y
        if (y > y1) y1 = y
      }
      rings.push({ ring, x0, x1, y0, y1 })
    }
}

/* Even-odd over every ring at once: a lake inside a continent is a hole. */
const isLand = (lon, lat) => {
  let inside = false
  for (const { ring, x0, x1, y0, y1 } of rings) {
    if (lon < x0 || lon > x1 || lat < y0 || lat > y1) continue
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i]
      const [xj, yj] = ring[j]
      if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside
    }
  }
  return inside
}

const bits = []
const rows = Math.floor((NORTH - SOUTH) / STEP) + 1
for (let r = 0; r < rows; r++) {
  const lat = NORTH - r * STEP
  const count = Math.max(1, Math.round((360 * Math.cos((lat * Math.PI) / 180)) / STEP))
  for (let i = 0; i < count; i++) {
    const lon = -180 + ((i + (r % 2) * 0.5) * 360) / count
    bits.push(isLand(lon, lat) ? 1 : 0)
  }
}
const bytes = new Uint8Array(Math.ceil(bits.length / 8))
bits.forEach((b, i) => {
  if (b) bytes[i >> 3] |= 1 << (i & 7)
})
const mask = Buffer.from(bytes).toString("base64")
const land = bits.reduce((a, b) => a + b, 0)

writeFileSync(
  new URL(`../${OUT}`, import.meta.url),
  `/* Generated by scripts/build-everything-globe-land.mjs from Natural Earth's 1:50m land (public domain). Do not edit; run the script. */
/** Rows of latitude from NORTH down to SOUTH, STEP degrees apart; each row holds round(360 cos(lat) / STEP) dots, odd rows shifted half a dot; bit k is the k-th dot, least significant bit first. */
export const EVERYTHING_LAND_STEP = ${STEP}
export const EVERYTHING_LAND_NORTH = ${NORTH}
export const EVERYTHING_LAND_SOUTH = ${SOUTH}
export const EVERYTHING_LAND_COUNT = ${land}
export const EVERYTHING_LAND_B64 =
  "${mask}"
`,
)
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) console.log(`${bits.length} dots, ${land} on land, ${mask.length} characters -> ${OUT}`)
