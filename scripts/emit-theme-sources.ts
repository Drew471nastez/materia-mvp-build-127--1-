/**
 * Writes themes/default/sources.generated.ts: every `.storelib` file under
 * themes/default, as one importable map from theme path to source. And
 * themes/default/section-types.generated.ts: only the section types, for the
 * code a visitor's browser runs (components/website-builder/sections/
 * registry.ts), which needs the names and must not carry the sources.
 *
 * The `.storelib` file is the source of truth and the thing the code editor
 * edits; the application cannot import a `.storelib` file, so this is how the
 * default theme's sections reach the bundle without a custom loader or
 * runtime filesystem access. tests/storelib-theme.test.ts fails when the
 * generated file is not what this would write.
 *
 *   npx tsx scripts/emit-theme-sources.ts
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const ROOT = join(process.cwd(), "themes/default")
const FOLDERS = ["layout", "sections", "blocks", "snippets"] as const

export function themeSources(): Record<string, string> {
  const out: Record<string, string> = {}
  for (const folder of FOLDERS) {
    let names: string[] = []
    try { names = readdirSync(join(ROOT, folder)) } catch { continue }
    for (const name of names.filter((n) => n.endsWith(".storelib")).sort()) {
      out[`${folder}/${name}`] = readFileSync(join(ROOT, folder, name), "utf8")
    }
  }
  return out
}

export function themeSourcesModule(): string {
  const entries = Object.entries(themeSources())
    .map(([path, src]) => `  ${JSON.stringify(path)}: ${JSON.stringify(src)},`)
    .join("\n")
  return [
    "// Generated by scripts/emit-theme-sources.ts from themes/default/**/*.storelib.",
    "// Do not edit: edit the .storelib file and run `npx tsx scripts/emit-theme-sources.ts`.",
    "",
    "export const DEFAULT_THEME_SOURCES: Record<string, string> = {",
    entries,
    "}",
    "",
  ].join("\n")
}

/**
 * The section types the theme writes as `.storelib` files, names only. The
 * map above is 600KB of source; the registry that picks a section's
 * component imported the list from it (lib/website-builder/storelib-schemas),
 * and with it every source, the schema parser, the validator and postcss,
 * into every published website's JavaScript (docs/audits/website-builder-
 * engine-2026-10.md, S1). tests/storelib-theme.test.ts holds the two files
 * to this script.
 */
export function sectionTypesModule(): string {
  const types = Object.keys(themeSources())
    .filter((p) => /^sections\/[a-z0-9_-]+\.storelib$/.test(p))
    .map((p) => p.slice("sections/".length, -".storelib".length))
  return [
    "// Generated by scripts/emit-theme-sources.ts from themes/default/sections/*.storelib.",
    "// Do not edit: add or remove the .storelib file and run `npx tsx scripts/emit-theme-sources.ts`.",
    "",
    "export const DEFAULT_STORELIB_SECTION_TYPES: readonly string[] = [",
    ...types.map((t) => `  ${JSON.stringify(t)},`),
    "]",
    "",
  ].join("\n")
}

if (process.argv[1] && process.argv[1].endsWith("emit-theme-sources.ts")) {
  const out = join(ROOT, "sources.generated.ts")
  writeFileSync(out, themeSourcesModule())
  console.log(`wrote ${out}`)
  const types = join(ROOT, "section-types.generated.ts")
  writeFileSync(types, sectionTypesModule())
  console.log(`wrote ${types}`)
}
