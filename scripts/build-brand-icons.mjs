/**
 * THE FEW BRAND MARKS WE USE, WITHOUT THE WHOLE SETS (build memory).
 *
 * react-icons/si is one 5 MB module and react-icons/fa6 one 1.7 MB module.
 * The bundler parses every byte of them for the browser and for the server
 * even when a page uses one icon, and the production build was at Vercel's
 * 8 GB build machine limit. This copies the icons the app imports (found by
 * scanning app/, components/ and lib/) into components/icons/brand-icons.generated.ts,
 * built with react-icons' own GenIcon, so every import keeps working.
 *
 * Run: node scripts/build-brand-icons.mjs (also checked by tests/brand-icons.test.ts).
 * Licences: react-icons MIT; Simple Icons CC0; Font Awesome Free icons CC BY 4.0
 * (https://fontawesome.com/license/free), credited here and in the generated file.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs"
import { join, dirname } from "node:path"
import { createRequire } from "node:module"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const require = createRequire(join(root, "package.json"))
const pkg = join(dirname(require.resolve("react-icons/lib")), "..")
const SETS = { si: "react-icons/si", fa6: "react-icons/fa6" }
const OUT = "components/icons/brand-icons.generated.ts"

const used = { si: new Set(), fa6: new Set() }
const walk = (dir) => {
  for (const e of readdirSync(join(root, dir))) {
    const rel = `${dir}/${e}`
    if (statSync(join(root, rel)).isDirectory()) { if (e !== "node_modules") walk(rel); continue }
    if (!/\.(ts|tsx)$/.test(e) || rel === OUT) continue
    const src = readFileSync(join(root, rel), "utf8")
    for (const m of src.matchAll(/\{([^}]*)\}\s*from\s*["'](react-icons\/(si|fa6)|@\/components\/icons\/brand-icons\.generated)["']/g)) {
      for (const n of m[1].split(",").map((x) => x.trim().split(/\s+as\s+/)[0]).filter(Boolean)) {
        if (n.startsWith("Si")) used.si.add(n); else if (n.startsWith("Fa")) used.fa6.add(n)
      }
    }
  }
}
for (const d of ["app", "components", "lib"]) walk(d)

const out = [
  "// THIS FILE IS GENERATED by scripts/build-brand-icons.mjs: only the brand marks the app imports.",
  "// Icons: Simple Icons (CC0 1.0), Font Awesome Free (CC BY 4.0, https://fontawesome.com/license/free), via react-icons (MIT).",
  'import { GenIcon, type IconBaseProps } from "react-icons/lib"',
  "",
]
for (const [set, names] of Object.entries(used)) {
  const src = readFileSync(join(pkg, set, "index.mjs"), "utf8")
  for (const name of [...names].sort()) {
    const at = src.indexOf(`export function ${name} (props) {`)
    if (at < 0) throw new Error(`${name} is not in ${SETS[set]}`)
    const body = src.slice(at, src.indexOf("\n};", at))
    const data = body.slice(body.indexOf("GenIcon(") + 8, body.lastIndexOf(")(props)"))
    out.push(`export function ${name}(props: IconBaseProps) {`, `  return GenIcon(${data})(props)`, "}", "")
  }
}
writeFileSync(join(root, OUT), out.join("\n"))
console.log(`wrote ${OUT} (${used.si.size} Simple Icons, ${used.fa6.size} Font Awesome)`)
