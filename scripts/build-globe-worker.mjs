/**
 * ===========================================================================
 *  THE HOME PAGE GLOBE'S WORKER, AS ONE STRING
 * ===========================================================================
 * The analytics section's globe (components/marketing/home/platform-globe.tsx)
 * is drawn in a worker where the browser can hand a canvas to one, so the
 * page's own thread does nothing per frame. The worker's code is
 * platform-globe-worker.ts, which draws with platform-globe-draw.ts, the
 * same drawing the page uses where it cannot. This bundles the two into one
 * plain script and writes it into platform-globe-worker-source.ts as a
 * string; the page starts the worker from that string (a blob: URL), so
 * there is no extra file to fetch and nothing for the bundler to resolve.
 *
 * Wave 13 perf: the "Sell to fans anywhere" globe (everything-globe.tsx)
 * is drawn the same way, by everything-globe-worker.ts with the engine in
 * everything-globe-draw.ts, written into everything-globe-worker-source.ts.
 *
 * Landing round 6: the three dot fields (the purple sheet's, the closing call's
 * and How it works') are drawn the same way, by dot-field-worker.ts with the
 * engine in dot-field-engine.ts, written into dot-field-worker-source.ts
 * (tests/home-landing-dotworker6.test.ts checks it is up to date).
 *
 * Run it after changing any of those files (tests/home-w12-platform.test.ts
 * and tests/home-w13-everything.test.ts check the strings are up to date):
 *
 *   node scripts/build-globe-worker.mjs
 */
import { writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { build } from "esbuild"

const ROOT = fileURLToPath(new URL("..", import.meta.url))
const ENTRY = "components/marketing/home/platform-globe-worker.ts"
const OUT = "components/marketing/home/platform-globe-worker-source.ts"
const EVERYTHING_ENTRY = "components/marketing/home/everything-globe-worker.ts"
const EVERYTHING_OUT = "components/marketing/home/everything-globe-worker-source.ts"
const DOT_FIELD_ENTRY = "components/marketing/home/dot-field-worker.ts"
const DOT_FIELD_OUT = "components/marketing/home/dot-field-worker-source.ts"

async function bundle(entry) {
  const result = await build({
    absWorkingDir: ROOT,
    entryPoints: [entry],
    bundle: true,
    format: "iife",
    target: "es2020",
    minify: true,
    legalComments: "none",
    write: false,
    logLevel: "silent",
  })
  return result.outputFiles[0].text.trim()
}

/** The bundled worker, as the string the page runs. */
export function globeWorkerSource() {
  return bundle(ENTRY)
}

/** The "Sell to fans anywhere" globe's worker, as the string the page runs. */
export function everythingGlobeWorkerSource() {
  return bundle(EVERYTHING_ENTRY)
}

/** The dot fields' worker, as the string the page runs. */
export function dotFieldWorkerSource() {
  return bundle(DOT_FIELD_ENTRY)
}

/** The file written beside the dot fields' worker. */
export function dotFieldWorkerModule(source) {
  return `/* Generated by scripts/build-globe-worker.mjs from dot-field-worker.ts and dot-field-engine.ts. Do not edit; run the script. */
export const DOT_FIELD_WORKER_SOURCE = ${JSON.stringify(source)}
`
}

/** The file written beside the worker. */
export function globeWorkerModule(source) {
  return `/* Generated by scripts/build-globe-worker.mjs from platform-globe-worker.ts and platform-globe-draw.ts. Do not edit; run the script. */
export const GLOBE_WORKER_SOURCE = ${JSON.stringify(source)}
`
}

/** The file written beside the "Sell to fans anywhere" globe's worker. */
export function everythingGlobeWorkerModule(source) {
  return `/* Generated by scripts/build-globe-worker.mjs from everything-globe-worker.ts and everything-globe-draw.ts. Do not edit; run the script. */
export const EVERYTHING_GLOBE_WORKER_SOURCE = ${JSON.stringify(source)}
`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(new URL(`../${OUT}`, import.meta.url), globeWorkerModule(await globeWorkerSource()))
  console.log(`wrote ${OUT}`)
  writeFileSync(new URL(`../${EVERYTHING_OUT}`, import.meta.url), everythingGlobeWorkerModule(await everythingGlobeWorkerSource()))
  console.log(`wrote ${EVERYTHING_OUT}`)
  writeFileSync(new URL(`../${DOT_FIELD_OUT}`, import.meta.url), dotFieldWorkerModule(await dotFieldWorkerSource()))
  console.log(`wrote ${DOT_FIELD_OUT}`)
}
