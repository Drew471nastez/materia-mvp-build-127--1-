const toPascalCase = (name: string) =>
  name
    .split("-")
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join("")

/**
 * Typed as an SVG component, not `{ className?: string }`. A lucide icon takes
 * every SVG prop, and a caller that passed `style` alongside `className` — the
 * benefits section does, to colour the icon — was a type error against the
 * narrower shape.
 */
export function getIconComponent(iconName: string): React.ComponentType<React.SVGProps<SVGSVGElement>> {
  if (ICON_ALIASES[iconName]) return ICON_ALIASES[iconName]
  const byName = ICON_REGISTRY[toPascalCase(iconName)]
  if (byName) return byName
  return CheckCircle
}
