/**
 * ===========================================================================
 *  THE WHOLE ICON LIBRARY WAS ON EVERY PRODUCT PAGE
 * ===========================================================================
 * `import * as LucideIcons from "lucide-react"` in the section renderer, and
 * the section renderer is imported by the product page, the creator page and
 * every published site. Measured on production, that one import was the
 * largest thing a visitor downloaded:
 *
 *     /_next/static/chunks/1aa56d81e44319aa.js   196 KB compressed
 *                                                794 KB raw, 1732 icon refs
 *
 * out of 674 KB of JavaScript on the page in total. For a product page that
 * draws, at most, a handful of small pictograms.
 *
 * A namespace import is not the mistake by itself; the mistake is what it was
 * for. The resolver looked an icon up by NAME at runtime —
 * `(LucideIcons as any)[pascalCase]` — and a bundler cannot know which names
 * will be asked for, so it has to keep all 1736 of them.
 *
 * ---------------------------------------------------------------------------
 *  AND NOTHING A CREATOR CHOSE IS LOST
 * ---------------------------------------------------------------------------
 * The runtime lookup was never open-ended in practice. The picker offers a
 * fixed list (BENEFIT_ICONS in sections-sidebar), and the renderer had its
 * own map of aliases. The registry below is the union of those two, filtered
 * to the names lucide actually ships: 243 icons. Every icon a creator can
 * pick still resolves, by the same kebab name and the same PascalCase
 * fallback as before, and an unknown name still lands on CheckCircle exactly
 * as it did.
 *
 * SO THIS FILE IS GENERATED FROM THOSE TWO LISTS. Adding an icon to the
 * picker means adding it here; tests/icon-weight.test.ts fails if the two
 * drift apart, and fails if the namespace import comes back.
 */
